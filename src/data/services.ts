export type PriceRow = {
  label: string;
  /** Пояснение под названием строки: «экспресс-прохождение», «775 ₽ / урок». */
  note?: string;
  price: Price;
  /** Вторая колонка: выходные и праздники. */
  weekend?: Price;
  /** Старая цена, зачёркнутая: «800 ₽ (вместо 1 000 ₽)». */
  old?: number;
  oldWeekend?: number;
};

export type PriceTable = {
  caption?: string;
  /** Заголовки колонок цен. Одна колонка — без заголовка. */
  columns?: string[];
  rows: PriceRow[];
  /** Подпись вместо пустой цены. */
  empty?: string;
};

export type Point = { title: string; text: string };
/** Строка-факт рядом с описанием: «Возраст», «Формат», «Вместимость». null — «Уточняется». */
export type Meta = { label: string; value: string | null };
export type Schedule = { days: string | null; slots: { label: string; time: string | null }[] };

export type Offer = {
  /** Якорь секции на странице. */
  id: string;
  title: string;
  subtitle?: string;
  badges: string[];
  /** Вводный абзац с подписью: «Для кого», «О секции». */
  intro?: { label: string; text: string };
  meta?: Meta[];
  points?: { title: string; items: Point[] };
  includes?: { title: string; items: string[] };
  schedule?: Schedule;
  prices?: PriceTable;
  /** Цены ещё нет и не будет до старта: подпись вместо таблицы. */
  soon?: string;
  /** Кнопка: без href — онлайн-запись (BookingLink), с href — якорь формы на странице. */
  cta: { label: string; href?: string };
  photo: PhotoKey;
};

