/** «от N ₽» для карточки услуги по её таблице цен. */
export const priceFrom = (offer: Offer) =>
  formatFrom(offer.prices?.rows.flatMap((r) => [r.price, r.weekend ?? null]) ?? [], offer.soon ?? 'Цена по запросу');
